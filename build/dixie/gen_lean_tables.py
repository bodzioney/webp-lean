#!/usr/bin/env python3
"""Generate webp-lean/WebP/Spec/VP8/Tables.lean from the RFC 6386 §20 C sources
(as extracted by extract_dixie.py).  Usage: python3 -I gen_lean_tables.py SRC_DIR OUT.lean

Every table is copied verbatim (flattened in C row-major order) from the named C array;
enum constants used in the tree tables are resolved with the values of the enums in
dixie.h (`enum prediction_mode`).
"""
import re, sys, os

src, out = sys.argv[1], sys.argv[2]

ENUM = {  # dixie.h enum prediction_mode (key-frame relevant part)
    "DC_PRED": 0, "V_PRED": 1, "H_PRED": 2, "TM_PRED": 3, "B_PRED": 4,
    "B_DC_PRED": 0, "B_TM_PRED": 1, "B_VE_PRED": 2, "B_HE_PRED": 3, "B_LD_PRED": 4,
    "B_RD_PRED": 5, "B_VR_PRED": 6, "B_VL_PRED": 7, "B_HD_PRED": 8, "B_HU_PRED": 9,
}

def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    return re.sub(r"//[^\n]*", " ", s)

def table(fname, name, macros=None):
    text = strip_comments(open(os.path.join(src, fname)).read())
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=]*\])?\s*=\s*\{", text)
    if not m:
        raise SystemExit(f"{name} not found in {fname}")
    i = m.end(); depth = 1
    while depth:
        c = text[i]
        depth += c == "{"; depth -= c == "}"; i += 1
    body = text[m.end():i - 1]
    if macros:
        for k, f in macros.items():
            body = re.sub(k + r"\((\d+)\)", lambda mm: str(f(int(mm.group(1)))), body)
    vals = []
    for tok in re.findall(r"-?\s*[A-Za-z_][A-Za-z_0-9]*|-?\s*\d+", body):
        tok = tok.replace(" ", "")
        neg = tok.startswith("-")
        t = tok.lstrip("-")
        v = ENUM[t] if t in ENUM else int(t)
        vals.append(-v if neg else v)
    return vals

def emit(f, lname, vals, doc, ty="Nat"):
    f.write(f"/-- {doc} -/\n")
    f.write(f"def {lname} : Array {ty} := #[\n")
    for k in range(0, len(vals), 16):
        chunk = vals[k:k + 16]
        f.write("  " + ", ".join(f"({v})" if v < 0 else str(v) for v in chunk))
        f.write(",\n" if k + 16 < len(vals) else "]\n\n")

tables = [
    ("dequant_data.h", "dc_q_lookup", "dcQLookup", 128, "Nat", "`dc_q_lookup[128]` (dequant_data.h, RFC 6386 §14.1)."),
    ("dequant_data.h", "ac_q_lookup", "acQLookup", 128, "Nat", "`ac_q_lookup[128]` (dequant_data.h, RFC 6386 §14.1)."),
    ("vp8_prob_data.h", "k_coeff_entropy_update_probs", "kCoeffEntropyUpdateProbs", 1056, "Nat",
     "`k_coeff_entropy_update_probs[4][8][3][11]` (vp8_prob_data.h, RFC 6386 §13.4), flattened."),
    ("vp8_prob_data.h", "k_default_coeff_probs", "kDefaultCoeffProbs", 1056, "Nat",
     "`k_default_coeff_probs[4][8][3][11]` (vp8_prob_data.h, RFC 6386 §13.5), flattened."),
    ("modemv_data.h", "kf_y_mode_probs", "kfYModeProbs", 4, "Nat", "`kf_y_mode_probs` (modemv_data.h, RFC 6386 §11.2)."),
    ("modemv_data.h", "kf_uv_mode_probs", "kfUvModeProbs", 3, "Nat", "`kf_uv_mode_probs` (modemv_data.h, RFC 6386 §11.2)."),
    ("modemv_data.h", "kf_b_mode_probs", "kfBModeProbs", 900, "Nat",
     "`kf_b_mode_probs[10][10][9]` (modemv_data.h, RFC 6386 §11.5), indexed `[above][left][node]`, flattened."),
    ("modemv_data.h", "kf_y_mode_tree", "kfYModeTree", 8, "Int", "`kf_y_mode_tree` (modemv_data.h, RFC 6386 §11.2)."),
    ("modemv_data.h", "uv_mode_tree", "uvModeTree", 6, "Int", "`uv_mode_tree` (modemv_data.h, RFC 6386 §11.2)."),
    ("modemv_data.h", "b_mode_tree", "bModeTree", 18, "Int", "`b_mode_tree` (modemv_data.h, RFC 6386 §11.2)."),
    ("tokens.c", "left_context_index", "leftContextIndex", 25, "Nat", "`left_context_index[25]` (tokens.c)."),
    ("tokens.c", "above_context_index", "aboveContextIndex", 25, "Nat", "`above_context_index[25]` (tokens.c)."),
    ("tokens.c", "zigzag", "zigzag", 16, "Nat", "`zigzag[16]` (tokens.c, RFC 6386 §13.2)."),
]

with open(out, "w") as f:
    f.write("/-!\n# RFC 6386 reference decoder tables\n\n"
            "GENERATED by `build/dixie/gen_lean_tables.py` from the C sources of RFC 6386 §20\n"
            "(extracted from `rfc6386.txt` by `build/dixie/extract_dixie.py`). Do not edit by hand.\n"
            "Multi-dimensional C arrays are flattened in row-major order.\n-/\n"
            "namespace WebP.Spec.VP8.Tables\n\n")
    for fname, cname, lname, n, ty, doc in tables:
        vals = table(fname, cname)
        assert len(vals) == n, (cname, len(vals))
        if ty == "Nat":
            assert min(vals) >= 0
        emit(f, lname, vals, doc, ty)
    # bands_x uses the macro X(n) = n * PREV_COEFF_CONTEXTS * ENTROPY_NODES = 33 n
    bx = table("tokens.c", "bands_x", {"X": lambda n: n * 3 * 11})
    assert len(bx) == 16
    emit(f, "bandsX", bx, "`bands_x[16]` (tokens.c): `X(band) = band * PREV_COEFF_CONTEXTS * ENTROPY_NODES`.")
    # extrabits[MAX_ENTROPY_TOKENS] = { min_val, length, probs[12] }
    eb = table("tokens.c", "extrabits")
    assert len(eb) == 12 * 14, len(eb)
    emit(f, "extrabitsMinVal", [eb[14 * k] for k in range(12)], "`extrabits[t].min_val` (tokens.c).", "Int")
    emit(f, "extrabitsLength", [eb[14 * k + 1] for k in range(12)], "`extrabits[t].length` (tokens.c).", "Int")
    emit(f, "extrabitsProbs", [p for k in range(12) for p in eb[14 * k + 2:14 * k + 14]],
         "`extrabits[t].probs[12]` (tokens.c), flattened `[t][i]`.")
    f.write("end WebP.Spec.VP8.Tables\n")
print("ok")
